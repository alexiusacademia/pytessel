#!/bin/sh
# Makes stdlib.tsl from lib/*.py: the modules of Python's standard library
# that PyTessel has written in Python (collections, itertools, re, …), as
# text inside the interpreter, so `import collections` needs no file.
#
#   tools/make-stdlib.sh      run it after changing anything in lib/
#
# Then build PyTessel again. Both lib/ and stdlib.tsl are kept in git.
cd "$(dirname "$0")/.." || exit 1
python3 - <<'EOF'
import os

def literal(text):
    # A Tessel string literal: its escapes are \n \r \t \" \\ \{ \}.
    out = []
    for c in text:
        if c == "\\":
            out.append("\\\\")
        elif c == '"':
            out.append('\\"')
        elif c == "{":
            out.append("\\{")
        elif c == "}":
            out.append("\\}")
        elif c == "\n":
            out.append("\\n")
        elif c == "\t":
            out.append("\\t")
        elif c == "\r":
            out.append("\\r")
        else:
            out.append(c)
    return '"' + "".join(out) + '"'

def function_name(module):
    return "bundled_" + module.replace(".", "_")

names = sorted(f[:-3] for f in os.listdir("lib") if f.endswith(".py"))
out = []
out.append("// Generated by tools/make-stdlib.sh from lib/*.py: don't change it by hand.")
out.append("//")
out.append("// The modules of the standard library that are written in Python, as text:")
out.append("// `import` runs them like a file's (see importModule in modules.tsl).")
out.append("")
out.append("fn bundledModules() -> [String] {")
out.append("    [" + ", ".join('"' + n + '"' for n in names) + "]")
out.append("}")
out.append("")
out.append("// A bundled module's Python text, or nil if there's none of that name.")
out.append("fn bundledModule(_ name: String) -> String? {")
for n in names:
    out.append('    if name == "' + n + '" {')
    out.append("        return " + function_name(n) + "()")
    out.append("    }")
out.append("    nil")
out.append("}")
for n in names:
    text = open(os.path.join("lib", n + ".py"), encoding="utf-8").read()
    # A piece for each line or so: one very long literal is slow to compile.
    lines = text.split("\n")
    pieces = []
    for i, line in enumerate(lines):
        pieces.append(line + ("\n" if i < len(lines) - 1 else ""))
    chunks = []
    size = 40
    for i in range(0, len(pieces), size):
        chunks.append("".join(pieces[i:i + size]))
    out.append("")
    out.append("fn " + function_name(n) + "() -> String {")
    out.append("    [")
    for chunk in chunks:
        if chunk:
            out.append("        " + literal(chunk) + ",")
    out.append("    ].joined()")
    out.append("}")
open("stdlib.tsl", "w", encoding="utf-8").write("\n".join(out) + "\n")
print("stdlib.tsl: " + ", ".join(names))
EOF
